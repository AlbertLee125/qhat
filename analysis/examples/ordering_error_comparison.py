"""Compare Pauli orderings for H, excited H, and H2 Trotter evolution.

This example uses two small Jordan-Wigner Hamiltonians generated by QHAT's
Hamiltonian generator and the repository's local configuration files:

* H/6-31G from ``local_configs/h_atom_631g_jw.py``
* H2/STO-3G from ``local_configs/h2_sto3g_jw.py``

The 6-31G basis gives atomic hydrogen two spatial orbitals.  We diagonalize
its one-electron sector and use the lowest two *distinct* energy levels as H
and excited H (H*).  For H2, we use the ground state in the two-electron
sector.

For each state, the example compares QHAT's requested ordering methods:

* ``None``: preserve the QHAT/OpenFermion input order
* ``lexicographical``: sort the dense Pauli strings
* ``group_evolve_greedy``: color the noncommutation graph and place equal
  colors, hence mutually commuting terms, next to one another

Run from the repository root with:

    python analysis/examples/ordering_error_comparison.py

The default is one first-order Trotter step at t=1 Hartree^-1.  A deliberately
coarse step makes ordering effects visible.  Use ``--help`` for controls.
"""

