@dataclass(frozen=True)
class EvolutionCase:
    """One physical state and the Hamiltonian used to evolve it."""

    name: str
    basis: str
    particle_number: int
    energy: float
    state: np.ndarray
    terms: Mapping[str, float]

    @property
    def num_qubits(self) -> int:
        return len(next(iter(self.terms)))


@dataclass(frozen=True)
class OrderingResult:
    """Exact numerical diagnostics for one state and one Pauli ordering."""

    case_name: str
    ordering_method: str | None
    energy: float
    operator_error: float
    state_error: float
    infidelity: float
    ordered_paulis: tuple[str, ...]

    @property
    def ordering_label(self) -> str:
        return ORDERING_LABELS[self.ordering_method]


def particle_sector_basis_indices(num_qubits: int, particle_number: int) -> list[int]:
    """Return computational-basis indices with the requested occupation count."""
    if not 0 <= particle_number <= num_qubits:
        raise ValueError(
            f"particle_number must be in 0..{num_qubits}, got {particle_number}."
        )
    return [
        index
        for index in range(2**num_qubits)
        if index.bit_count() == particle_number
    ]


def particle_sector_eigenstate(
    terms: Mapping[str, float],
    particle_number: int,
    distinct_level: int,
    energy_tolerance: float = 1e-9,
) -> tuple[float, np.ndarray]:
    """Return one eigenstate from a distinct energy level in a particle sector.

    Spin degeneracy means the first two one-electron eigenvectors of atomic H
    can have the same energy. ``distinct_level=1`` skips that duplicate energy
    and selects the first genuine orbital excitation.
    """
    if not terms:
        raise ValueError("At least one Pauli term is required.")
    if distinct_level < 0:
        raise ValueError("distinct_level must be nonnegative.")

    num_qubits = len(next(iter(terms)))
    hamiltonian = pauli_dict_to_matrix(terms, num_qubits)
    sector_indices = particle_sector_basis_indices(num_qubits, particle_number)
    sector_hamiltonian = hamiltonian[np.ix_(sector_indices, sector_indices)]
    energies, vectors = np.linalg.eigh(sector_hamiltonian)

    distinct_positions = [0]
    for position in range(1, len(energies)):
        previous = energies[distinct_positions[-1]]
        if abs(energies[position] - previous) > energy_tolerance:
            distinct_positions.append(position)

    if distinct_level >= len(distinct_positions):
        raise ValueError(
            f"Particle sector has only {len(distinct_positions)} distinct energy "
            f"levels; requested level {distinct_level}."
        )

    selected = distinct_positions[distinct_level]
    state = np.zeros(2**num_qubits, dtype=complex)
    state[sector_indices] = vectors[:, selected]
    return float(energies[selected]), state


def build_evolution_cases() -> list[EvolutionCase]:
    """Construct H, H*, and H2 states from fixed-particle-number sectors."""
    h_terms = dict(H_ATOM_631G_JW_TERMS)
    h_ground_energy, h_ground = particle_sector_eigenstate(h_terms, 1, 0)
    h_excited_energy, h_excited = particle_sector_eigenstate(h_terms, 1, 1)

    h2_terms = dict(H2_STO3G_GENERATED_JW_TERMS)
    h2_ground_energy, h2_ground = particle_sector_eigenstate(h2_terms, 2, 0)

    return [
        EvolutionCase(
            name="H ground",
            basis="H/6-31G, one-electron sector",
            particle_number=1,
            energy=h_ground_energy,
            state=h_ground,
            terms=h_terms,
        ),
        EvolutionCase(
            name="H excited",
            basis="H/6-31G, first distinct excited orbital",
            particle_number=1,
            energy=h_excited_energy,
            state=h_excited,
            terms=h_terms,
        ),
        EvolutionCase(
            name="H2 ground",
            basis="H2/STO-3G at 0.7414 Angstrom, two-electron sector",
            particle_number=2,
            energy=h2_ground_energy,
            state=h2_ground,
            terms=h2_terms,
        ),
    ]


def dense_terms_to_sparse(
    terms: Mapping[str, float],
) -> list[tuple[tuple[tuple[int, str], ...], complex]]:
    """Convert QHAT dense Pauli strings to product-formula term tuples."""
    return [
        (dense_string_to_pauli_key(pauli), complex(coefficient))
        for pauli, coefficient in terms.items()
    ]


def noncommutation_graph(terms: Mapping[str, float]) -> nx.Graph:
    """Build QHAT's graph whose edges connect noncommuting Pauli terms."""
    return create_commutativity_graph(
        list(terms.items()),
        pauli_string_format="explicit",
    )


def evaluate_ordering(
    case: EvolutionCase,
    ordering_method: str | None,
    time: float = 1.0,
    num_steps: int = 1,
    method: int = 1,
) -> OrderingResult:
    """Compare one QHAT ordering with exact time evolution."""
    if time < 0:
        raise ValueError("time must be nonnegative.")
    if num_steps <= 0:
        raise ValueError("num_steps must be positive.")

    ordered_terms = reorder_paulis(case.terms, ordering_method)
    sparse_terms = dense_terms_to_sparse(ordered_terms)
    hamiltonian = pauli_dict_to_matrix(case.terms, case.num_qubits)

    exact = exact_unitary(hamiltonian, time)
    trotter = dense_trotter_unitary(
        term_list=sparse_terms,
        time=time,
        num_steps=num_steps,
        n_qubits=case.num_qubits,
        method=method,
    )

    difference = trotter - exact
    exact_state = exact @ case.state
    trotter_state = trotter @ case.state
    overlap = np.vdot(trotter_state, exact_state)
    infidelity = float(np.clip(1.0 - abs(overlap) ** 2, 0.0, 1.0))

    return OrderingResult(
        case_name=case.name,
        ordering_method=ordering_method,
        energy=case.energy,
        operator_error=float(np.linalg.norm(difference, ord=2)),
        state_error=float(np.linalg.norm(trotter_state - exact_state)),
        infidelity=infidelity,
        ordered_paulis=tuple(ordered_terms),
    )


def run_ordering_experiments(
    cases: Sequence[EvolutionCase] | None = None,
    ordering_methods: Sequence[str | None] = ORDERING_METHODS,
    time: float = 1.0,
    num_steps: int = 1,
    method: int = 1,
) -> list[OrderingResult]:
    """Evaluate every requested ordering for every physical case."""
    selected_cases = build_evolution_cases() if cases is None else list(cases)
    return [
        evaluate_ordering(case, ordering, time, num_steps, method)
        for case in selected_cases
        for ordering in ordering_methods
    ]


def print_system_summary(cases: Sequence[EvolutionCase]) -> None:
    """Print state energies and graph-coloring structure for each Hamiltonian."""
    print("Physical Systems")
    print("----------------")
    seen_term_sets: set[tuple[str, ...]] = set()
    for case in cases:
        print(
            f"{case.name:10s}: E = {case.energy:+.12f} Hartree; "
            f"N = {case.particle_number}; {case.basis}"
        )

        signature = tuple(case.terms)
        if signature in seen_term_sets:
            continue
        seen_term_sets.add(signature)

        graph, _, groups = build_greedy_coloring_groups(case.terms)
        assert all(group_is_pairwise_commuting(group) for group in groups)
        print(
            f"             {len(case.terms)} Pauli terms, "
            f"{graph.number_of_edges()} noncommuting pairs, "
            f"{len(groups)} greedy commuting groups"
        )
    print()


def print_results(
    results: Sequence[OrderingResult],
    time: float,
    num_steps: int,
    method: int,
) -> None:
    """Print a compact comparison table."""
    formula = "first" if method == 1 else "second" if method == 2 else str(method)
    print("Trotter Error Comparison")
    print("-------------------------")
    print(f"formula = {formula} order; time = {time}; steps = {num_steps}")
    print()
    print(
        f"{'state':11s} {'ordering':18s} {'operator error':>16s} "
        f"{'state error':>16s} {'infidelity':>16s}"
    )
    for result in results:
        print(
            f"{result.case_name:11s} {result.ordering_label:18s} "
            f"{result.operator_error:16.8e} {result.state_error:16.8e} "
            f"{result.infidelity:16.8e}"
        )


def print_orders(results: Sequence[OrderingResult]) -> None:
    """Print every matrix-product Pauli order used in the comparison."""
    print()
    print("Pauli Orders")
    print("------------")
    seen: set[tuple[tuple[str, ...], str | None]] = set()
    for result in results:
        key = (result.ordered_paulis, result.ordering_method)
        if key in seen:
            continue
        seen.add(key)
        print(f"{result.case_name} / {result.ordering_label}")
        print("  " + " -> ".join(result.ordered_paulis))


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--time", type=float, default=1.0)
    parser.add_argument("--steps", type=int, default=1)
    parser.add_argument(
        "--method",
        type=int,
        choices=(1, 2),
        default=1,
        help="QHAT product formula: 1=first order, 2=second order",
    )
    parser.add_argument(
        "--show-orders",
        action="store_true",
        help="Print the dense Pauli sequence produced by every ordering",
    )
    args = parser.parse_args()

    cases = build_evolution_cases()
    results = run_ordering_experiments(
        cases=cases,
        time=args.time,
        num_steps=args.steps,
        method=args.method,
    )

    print("H, Excited H, And H2 Pauli-Ordering Experiment")
    print("================================================")
    print()
    print_system_summary(cases)
    print_results(results, args.time, args.steps, args.method)
    if args.show_orders:
        print_orders(results)


if __name__ == "__main__":
    main()
